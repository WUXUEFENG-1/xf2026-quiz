-- 云南工业信息职业学院 第二届“学宪法 讲宪法”校园知识竞赛（单人赛）
-- Supabase 建表脚本：在 Supabase 控制台 → SQL Editor 中整段执行即可。
-- 执行完成后到 Project Settings → API 复制 Project URL 与 anon public key，
-- 填入 app.js 顶部的 SUPABASE_URL / SUPABASE_ANON_KEY 两个常量。

-- 1. 报名表
create table if not exists public.registrations (
  id          bigint generated by default as identity primary key,
  sid         text not null unique,              -- 学号，一学号一条报名
  name        text not null,
  dept        text not null,                     -- 系（部）
  class       text not null,                     -- 班级
  phone       text,
  created_at  text not null default to_char(now() at time zone 'Asia/Shanghai', 'YYYY-MM-DD HH24:MI')
);

-- 2. 成绩表（同一学号可多次作答，榜单取最好成绩）
create table if not exists public.results (
  id          bigint generated by default as identity primary key,
  sid         text not null,
  name        text not null,
  dept        text,
  class       text,
  score       int  not null check (score >= 0 and score <= 100),
  right       int  not null default 0,
  wrong       int  not null default 0,
  used        int  not null default 0,           -- 作答用时（秒）
  detail      jsonb,                             -- 分题型明细 {"s":{t,r},"m":{t,r},"j":{t,r}}
  created_at  text not null default to_char(now() at time zone 'Asia/Shanghai', 'YYYY-MM-DD HH24:MI')
);

create index if not exists idx_results_sid      on public.results (sid);
create index if not exists idx_results_rank     on public.results (score desc, used asc);
create index if not exists idx_results_dept     on public.results (dept);
create index if not exists idx_reg_dept         on public.registrations (dept);

-- 3. 行级安全（RLS）：前端只使用 anon key，因此只开放“报名插入/读取”和“成绩插入/读取”
alter table public.registrations enable row level security;
alter table public.results       enable row level security;

drop policy if exists reg_select on public.registrations;
create policy reg_select on public.registrations
  for select to anon using (true);

drop policy if exists reg_insert on public.registrations;
create policy reg_insert on public.registrations
  for insert to anon with check (true);

drop policy if exists res_select on public.results;
create policy res_select on public.results
  for select to anon using (true);

-- 成绩仅允许插入，且分数、用时做基本约束，防止前端误写脏数据
drop policy if exists res_insert on public.results;
create policy res_insert on public.results
  for insert to anon with check (
    score between 0 and 100
    and used between 0 and 3600
    and length(sid) between 6 and 20
  );

-- 说明：
-- 1) 管理端删除功能在云端模式下被禁用，需要清理记录时请在本控制台 Table Editor 操作；
-- 2) 若需要更严格的防刷分策略（如同一学号 24 小时内最多提交 N 次），
--    可另建 RPC 函数并在前端改为调用 RPC，当前版本未启用；
-- 3) 生产环境如需关闭公开读取，可将 reg_select / res_select 改为仅 service_role 可读，
--    改造前端为经 Edge Function 取榜单。
